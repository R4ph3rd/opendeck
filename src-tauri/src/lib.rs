/// Error returned by commands. Serialized as a tagged union for the UI.
#[derive(Debug, Clone, Serialize, Deserialize, Type)]
#[serde(tag = "kind", content = "message", rename_all = "snake_case")]
pub enum CommandError {
    /// Internal state could not be accessed (poisoned lock, settings file).
    Internal(String),
    /// The audio engine is stopped or a device call failed.
    Audio(String),
    /// A file could not be read or decoded, or is too long.
    Media(String),
}

impl From<CoreError> for CommandError {
    fn from(err: CoreError) -> Self {
        let message = err.to_string();
        match err {
            CoreError::NotRunning | CoreError::NoEngine(_) | CoreError::Audio(_) => {
                CommandError::Audio(message)
            }
            CoreError::Media(_) | CoreError::TooLong { .. } | CoreError::Cancelled => {
                CommandError::Media(message)
            }
            CoreError::Settings(_) => CommandError::Internal(message),
        }
    }
}

/// Shared application state managed by Tauri.
pub struct AppState {
    core: Mutex<AppCore>,
}

impl AppState {
    /// Wraps a core.
    pub fn new(core: AppCore) -> Self {
        Self {
            core: Mutex::new(core),
        }
    }

    /// Clone of the core; the lock is not held while a command waits.
    fn snapshot(&self) -> Result<AppCore, CommandError> {
        self.core
            .lock()
            .map(|core| core.clone())
            .map_err(|e| CommandError::Internal(e.to_string()))
    }

    fn audio(&self) -> Result<AudioController, CommandError> {
        Ok(self.snapshot()?.audio()?)
    }
}

fn with_core<T>(
    state: &tauri::State<'_, AppState>,
    f: impl FnOnce(&mut AppCore) -> T,
) -> Result<T, CommandError> {
    let mut core = state
        .core
        .lock()
        .map_err(|e| CommandError::Internal(e.to_string()))?;
    Ok(f(&mut core))
}

/// Runs blocking core work off the async runtime's reactor threads.
async fn blocking<T: Send + 'static>(
    work: impl FnOnce() -> Result<T, CoreError> + Send + 'static,
) -> Result<T, CommandError> {
    tauri::async_runtime::spawn_blocking(work)
        .await
        .map_err(|e| CommandError::Internal(e.to_string()))?
        .map_err(CommandError::from)
}

/// Returns build and platform information.
#[tauri::command]
#[specta::specta]
fn app_info() -> AppInfo {
    AppInfo {
        name: opendeck_app_core::PRODUCT_NAME.to_owned(),
        version: opendeck_app_core::VERSION.to_owned(),
        tauri_version: tauri::VERSION.to_owned(),
        os: std::env::consts::OS.to_owned(),
        arch: std::env::consts::ARCH.to_owned(),
        max_decks: MAX_DECKS as u8,
        visible_decks: MVP_DECKS as u8,
    }
}

/// Lists the audio host APIs the platform reports.
#[tauri::command]
#[specta::specta]
fn list_audio_hosts(state: tauri::State<'_, AppState>) -> Result<Vec<AudioHostInfo>, CommandError> {
    with_core(&state, |core| core.audio_hosts())
}

/// Lists output devices of a host (`None` for the platform default).
#[tauri::command]
#[specta::specta]
async fn list_audio_devices(
    state: tauri::State<'_, AppState>,
    host: Option<AudioHostKind>,
) -> Result<Vec<AudioDeviceInfo>, CommandError> {
    let core = state.snapshot()?;
    blocking(move || core.audio_devices(host)).await
}

