    #[test]
    fn load_track_returns_tags_and_plays() {
        let dir = std::env::temp_dir().join(format!("opendeck-shell-{}", std::process::id()));
        std::fs::create_dir_all(&dir).expect("temp dir");
        let wav = dir.join("tone.wav");
        write_wav(&wav);

        let app = offline_app();
        let events = app
            .state::<AppState>()
            .audio()
            .expect("audio")
            .subscribe()
            .expect("subscribe");
        let info = tauri::async_runtime::block_on(load_track(
            app.state(),
            deck_a(),
            wav.to_string_lossy().into_owned(),
        ))
        .expect("load");
        assert_eq!(info.file_name, "tone.wav");

        let deadline = Instant::now() + Duration::from_secs(10);
        let mut loaded = false;
        while Instant::now() < deadline && !loaded {
            if let Ok(CoreEvent::TrackLoaded(t)) = events.recv_timeout(Duration::from_millis(100)) {
                loaded = t.deck == deck_a();
            }
        }
        assert!(loaded, "track-loaded never arrived");

        toggle_playing(app.state(), deck_a()).expect("play");
        let mut advanced = false;
        while Instant::now() < deadline && !advanced {
            if let Ok(CoreEvent::Telemetry(t)) = events.recv_timeout(Duration::from_millis(100)) {
                advanced = t.decks[0].playing && t.decks[0].position.0 > 0;
            }
        }
        assert!(advanced, "playhead never advanced");
        let _ = std::fs::remove_dir_all(&dir);
    }

