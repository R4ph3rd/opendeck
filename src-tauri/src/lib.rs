//! OpenDeck desktop shell (Tauri 2).
//!
//! Thin layer: every command forwards to `opendeck_app_core`. Commands and
//! events are declared once here and exported to TypeScript with
//! tauri-specta (ADR 0004). Run `cargo run -p opendeck-desktop --bin
//! export-bindings` after changing any of them; CI regenerates the file and
//! fails on a diff.

use std::path::Path;
use std::sync::Mutex;

use opendeck_app_core::AppCore;
use opendeck_contracts::pad::PadMode;
use opendeck_contracts::settings::AudioHostInfo;
use opendeck_contracts::{DeckId, EngineTelemetry, MAX_DECKS, MVP_DECKS};
use serde::{Deserialize, Serialize};
use specta::Type;
use specta_typescript::Typescript;
use tauri_specta::{Builder, Event, collect_commands, collect_events};

/// Path of the generated bindings, relative to this crate's manifest directory.
pub const BINDINGS_PATH: &str = "../ui/src/ipc/bindings.ts";

/// Header written at the top of the generated bindings file.
const BINDINGS_HEADER: &str = "// Generated by tauri-specta from src-tauri. Do not edit.\n// Regenerate: cargo run -p opendeck-desktop --bin export-bindings\n";

/// Static information about the running build.
#[derive(Debug, Clone, Serialize, Deserialize, Type)]
pub struct AppInfo {
    /// Product name.
    pub name: String,
    /// Workspace version.
    pub version: String,
    /// Tauri runtime version.
    pub tauri_version: String,
    /// Target OS (`windows`, `macos`, `linux`).
    pub os: String,
    /// Target architecture (`x86_64`, `aarch64`).
    pub arch: String,
    /// Decks the engine architecture supports.
    pub max_decks: u8,
    /// Decks the MVP UI shows.
    pub visible_decks: u8,
}

/// Error returned by commands. Serialized as a tagged union for the UI.
#[derive(Debug, Clone, Serialize, Deserialize, Type)]
#[serde(tag = "kind", content = "message", rename_all = "snake_case")]
pub enum CommandError {
    /// Internal state could not be accessed (poisoned lock).
    Internal(String),
}

/// Shared application state managed by Tauri.
pub struct AppState(pub Mutex<AppCore>);

fn with_core<T>(
    state: &tauri::State<'_, AppState>,
    f: impl FnOnce(&mut AppCore) -> T,
) -> Result<T, CommandError> {
    let mut core = state
        .0
        .lock()
        .map_err(|e| CommandError::Internal(e.to_string()))?;
    Ok(f(&mut core))
}

/// Returns build and platform information.
#[tauri::command]
#[specta::specta]
fn app_info() -> AppInfo {
    AppInfo {
        name: opendeck_app_core::PRODUCT_NAME.to_owned(),
        version: opendeck_app_core::VERSION.to_owned(),
        tauri_version: tauri::VERSION.to_owned(),
        os: std::env::consts::OS.to_owned(),
        arch: std::env::consts::ARCH.to_owned(),
        max_decks: MAX_DECKS as u8,
        visible_decks: MVP_DECKS as u8,
    }
}

/// Lists audio host APIs (stub until milestone 1, see `AppCore::audio_hosts`).
#[tauri::command]
#[specta::specta]
fn list_audio_hosts(state: tauri::State<'_, AppState>) -> Result<Vec<AudioHostInfo>, CommandError> {
    with_core(&state, |core| core.audio_hosts())
}

/// Returns the active pad mode of a deck.
#[tauri::command]
#[specta::specta]
fn get_pad_mode(state: tauri::State<'_, AppState>, deck: DeckId) -> Result<PadMode, CommandError> {
    with_core(&state, |core| core.pad_mode(deck))
}

/// Engine snapshot pushed to the UI at ~60 Hz (ADR 0003, ADR 0004).
#[derive(Debug, Clone, Serialize, Deserialize, Type, Event)]
#[tauri_specta(event_name = "engine-telemetry")]
pub struct EngineTelemetryEvent(pub EngineTelemetry);

/// The tauri-specta builder holding every command and event. Used by the app
/// and by the bindings exporter, so both always agree.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![app_info, list_audio_hosts, get_pad_mode])
        .events(collect_events![EngineTelemetryEvent])
        // IDs (SQLite rowids) and frame counts are u64/i64 but stay far below
        // 2^53, so they are exported as `number` (ADR 0004).
        .dangerously_cast_bigints_to_number()
        // Every DTO has the same serialize and deserialize shape; one TS type each.
        .disable_serde_phases()
}

/// Writes the TypeScript bindings to `path`.
pub fn export_bindings(path: &Path) -> Result<(), specta_typescript::Error> {
    specta_builder().export(Typescript::default().header(BINDINGS_HEADER), path)
}

/// Starts the application.
pub fn run() {
    let builder = specta_builder();
    tauri::Builder::default()
        .manage(AppState(Mutex::new(AppCore::new())))
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running OpenDeck");
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Fails when `ui/src/ipc/bindings.ts` is stale.
    #[test]
    fn bindings_are_up_to_date() {
        let dir = std::env::temp_dir().join(format!("opendeck-bindings-{}", std::process::id()));
        std::fs::create_dir_all(&dir).expect("temp dir");
        let fresh = dir.join("bindings.ts");
        export_bindings(&fresh).expect("export bindings");
        let fresh = std::fs::read_to_string(&fresh).expect("read fresh bindings");
        let committed = Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_PATH);
        let committed = std::fs::read_to_string(committed).unwrap_or_default();
        assert!(
            fresh == committed,
            "ui/src/ipc/bindings.ts is stale: run `cargo run -p opendeck-desktop --bin export-bindings`"
        );
        let _ = std::fs::remove_dir_all(&dir);
    }

    /// Every contracts DTO planned for IPC (docs/ipc.md) must export to TypeScript.
    #[test]
    fn contract_dtos_export() {
        use opendeck_contracts::{
            analysis, beatgrid, control, cue, deck, fx, jobs, key, mixer, settings, telemetry,
        };
        let builder = specta_builder()
            .typ::<deck::DeckState>()
            .typ::<mixer::MixerState>()
            .typ::<telemetry::EngineEvent>()
            .typ::<cue::Cue>()
            .typ::<cue::LoopRegion>()
            .typ::<beatgrid::BeatGrid>()
            .typ::<key::MusicalKey>()
            .typ::<control::ControlEvent>()
            .typ::<control::FeedbackTarget>()
            .typ::<control::FeedbackValue>()
            .typ::<fx::EffectInfo>()
            .typ::<fx::FxPreset>()
            .typ::<opendeck_contracts::FxSlotId>()
            .typ::<jobs::JobProgress>()
            .typ::<analysis::AnalysisFeatures>()
            .typ::<analysis::Loudness>()
            .typ::<settings::AudioSettings>();
        let dir = std::env::temp_dir().join(format!("opendeck-dtos-{}", std::process::id()));
        std::fs::create_dir_all(&dir).expect("temp dir");
        let out = dir.join("dtos.ts");
        builder
            .export(Typescript::default(), &out)
            .expect("all contract DTOs export");
        let text = std::fs::read_to_string(&out).expect("read export");
        assert!(text.contains("export type ControlAction"));
        assert!(text.contains("export type MusicalKey = string"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn app_info_reports_decks() {
        let info = app_info();
        assert_eq!(info.name, "OpenDeck");
        assert_eq!(info.max_decks, 4);
        assert_eq!(info.visible_decks, 2);
    }
}
