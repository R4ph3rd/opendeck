/// File extensions the decoder accepts, lower case, without the dot.
#[tauri::command]
#[specta::specta]
fn supported_audio_extensions() -> Vec<String> {
    opendeck_media::SUPPORTED_EXTENSIONS
        .iter()
        .map(|e| (*e).to_owned())
        .collect()
}

/// Reads the tags of an audio file and queues its decode into `deck`.
/// Returns once the tags are known; `track-loaded` or `track-load-failed`
/// follows when the decode ends.
#[tauri::command]
#[specta::specta]
async fn load_track(
    state: tauri::State<'_, AppState>,
    deck: DeckId,
    path: String,
) -> Result<TrackInfo, CommandError> {
    let audio = state.audio()?;
    blocking(move || audio.load_track(deck, Path::new(&path))).await
}

