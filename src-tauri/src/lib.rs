/// Engine snapshot pushed to the UI at ~60 Hz (ADR 0003, ADR 0004).
#[derive(Debug, Clone, Serialize, Deserialize, Type, Event)]
#[tauri_specta(event_name = "engine-telemetry")]
pub struct EngineTelemetryEvent(pub EngineTelemetry);

/// A discrete engine or device notification (track ended, device lost).
#[derive(Debug, Clone, Serialize, Deserialize, Type, Event)]
#[tauri_specta(event_name = "engine-event")]
pub struct EngineEventEvent(pub EngineEvent);

/// A track is decoded and handed to the engine.
#[derive(Debug, Clone, Serialize, Deserialize, Type, Event)]
#[tauri_specta(event_name = "track-loaded")]
pub struct TrackLoadedEvent(pub TrackLoaded);

/// A decode failed.
#[derive(Debug, Clone, Serialize, Deserialize, Type, Event)]
#[tauri_specta(event_name = "track-load-failed")]
pub struct TrackLoadFailedEvent(pub TrackLoadFailed);

/// The audio stream was (re)started or stopped.
#[derive(Debug, Clone, Serialize, Deserialize, Type, Event)]
#[tauri_specta(event_name = "audio-device-changed")]
pub struct AudioDeviceChangedEvent(pub AudioStatus);

/// The tauri-specta builder holding every command and event. Used by the app
/// and by the bindings exporter, so both always agree.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            app_info,
            list_audio_hosts,
            list_audio_devices,
            get_audio_settings,
            set_audio_settings,
            get_audio_status,
            supported_audio_extensions,
            load_track,
            eject_track,
            set_playing,
            toggle_playing,
            cue,
            seek,
            set_tempo_fader,
            set_tempo_range,
            set_key_lock,
            pitch_bend,
            get_pad_mode,
        ])
        .events(collect_events![
            EngineTelemetryEvent,
            EngineEventEvent,
            TrackLoadedEvent,
            TrackLoadFailedEvent,
            AudioDeviceChangedEvent
        ])
        // IDs (SQLite rowids) and frame counts are u64/i64 but stay far below
        // 2^53, so they are exported as `number` (ADR 0004).
        .dangerously_cast_bigints_to_number()
        // Every DTO has the same serialize and deserialize shape; one TS type each.
        .disable_serde_phases()
}

/// Writes the TypeScript bindings to `path`.
pub fn export_bindings(path: &Path) -> Result<(), specta_typescript::Error> {
    specta_builder().export(Typescript::default().header(BINDINGS_HEADER), path)
}

/// Forwards core events to the webview until the core shuts down.
fn forward_events(app: tauri::AppHandle, events: crossbeam_channel::Receiver<CoreEvent>) {
    for event in events {
        let result = match event {
            CoreEvent::Telemetry(t) => EngineTelemetryEvent(*t).emit(&app),
            CoreEvent::Engine(e) => EngineEventEvent(e).emit(&app),
            CoreEvent::TrackLoaded(t) => TrackLoadedEvent(t).emit(&app),
            CoreEvent::TrackLoadFailed(f) => TrackLoadFailedEvent(f).emit(&app),
            CoreEvent::AudioStatus(s) => AudioDeviceChangedEvent(s).emit(&app),
        };
        if let Err(err) = result {
            eprintln!("could not emit event: {err}");
        }
    }
}

/// Starts the application.
pub fn run() {
    let builder = specta_builder();
    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let store = match app.path().app_config_dir() {
                Ok(dir) => SettingsStore::in_dir(&dir),
                Err(_) => SettingsStore::memory(),
            };
            let backend = if std::env::var_os(OFFLINE_AUDIO_ENV).is_some_and(|v| !v.is_empty()) {
                Backend::Offline {
                    sample_rate: 48_000,
                }
            } else {
                Backend::Device
            };
            let core = AppCore::launch(LaunchOptions {
                backend,
                store,
                ..LaunchOptions::default()
            })?;
            let events = core.audio()?.subscribe()?;
            let handle = app.handle().clone();
            std::thread::Builder::new()
                .name("opendeck-events".into())
                .spawn(move || forward_events(handle, events))?;
            app.manage(AppState::new(core));
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running OpenDeck");
}

